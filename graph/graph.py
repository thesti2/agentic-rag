from dotenv import load_dotenv
from langgraph.graph import START, END, StateGraph
from graph.consts import RETRIEVE, GENERATE, GRADE_DOCUMENTS, WEBSEARCH
from graph.nodes import generate, grade_documents, retrieve, web_search
from graph.state import GraphState
from graph.chains.answer_grader import answer_grader
from graph.chains.hallucination_grader import hallucination_grader
from graph.chains.router import question_router, RouteQuery

load_dotenv()



def decide_to_generate(state):
    print("--ASSESS WEB SEARCH--")

    if state["web_search"]:
        print("--DECIDE WEB SEARCH--")
        return WEBSEARCH
    else:
        return GENERATE


def grade_generation_grounded_in_documents_and_question(state: GraphState) -> str:
    print("--CHECK HALLUCINATIONS--")
    
    question = state["question"]
    documents = state["documents"]
    generation = state["generation"]

    # hallucination grader check whether the answer generated by LLM is based on the fact in the document
    score = hallucination_grader.invoke(
        {"documents": documents, "generation": generation}
    )

    if score.binary_score:  # True = answer is grounded in the documents
        print("-- GRADE GENERATION VS QUESTION")

        # answer grader check whether the answer generated by LLM is answering the question or not
        score = answer_grader.invoke({"question": question, "generation": generation})

        if score.binary_score:  # True = answer addresses the question
            print("-- DECISION: GENERATION ADRESSES QUESTION--")
            return "useful"
        else:            
            return "not useful"
    else:
        return "not supported"


def route_question(state: GraphState) -> str:
    print("--ROUTE QUESTION--")
    question = state["question"]

    result = question_router.invoke({"question": question})

    # Must match the Literal values in RouteQuery.datasource ("vectorstore" / "websearch")
    if result.datasource == WEBSEARCH:
        print("--ROUTE QUESTION TO WEB SEARCH--")
        return WEBSEARCH
    elif result.datasource == "vectorstore":
        print("--ROUTE QUESTION TO RAG--")
        return RETRIEVE
    raise ValueError(f"Unexpected datasource from router: {result.datasource!r}")
    


workflow = StateGraph(GraphState)


workflow.add_node(RETRIEVE, retrieve)
workflow.add_node(GRADE_DOCUMENTS, grade_documents)
workflow.add_node(GENERATE, generate)
workflow.add_node(WEBSEARCH, web_search)

# workflow.add_edge(START, RETRIEVE)
workflow.add_conditional_edges(START, route_question, [WEBSEARCH, RETRIEVE])
workflow.add_edge(RETRIEVE, GRADE_DOCUMENTS)
workflow.add_conditional_edges(GRADE_DOCUMENTS, decide_to_generate, [WEBSEARCH, GENERATE])
workflow.add_edge(WEBSEARCH, GENERATE)
# No plain GENERATE -> END edge: the conditional edge below decides where GENERATE goes
workflow.add_conditional_edges(
    GENERATE, 
    grade_generation_grounded_in_documents_and_question, 
    {
        "not supported": GENERATE,
        "useful": END,
        "not useful": WEBSEARCH
    }
)

app = workflow.compile()

app.get_graph().draw_mermaid_png(output_file_path="graph.png")

